import type { ContributorDirectory, FrameworkGroup, PageEntry } from './types.js'

// Read-only access to the Frameworks docs repo.
// No auth, no tokens: the browser talks directly to GitHub's public read
// endpoints. Anything that needs the user's GitHub token lives in the backend
// (functions/).

export const REPO = 'security-alliance/frameworks'
// PRs target `develop`, never `main`. It is also the repo's default branch.
export const BRANCH = 'develop'

// GitHub's own list of apps a user has authorized — the only place access to
// their account can actually be withdrawn. Signing out of the wizard clears our
// session; it does not, and cannot, undo the authorization held at GitHub.
export const REVOKE_URL = 'https://github.com/settings/apps/authorizations'

const DOCS_ROOT = 'docs/pages/'

/** One entry of GitHub's git-tree listing. */
interface TreeNode {
  path: string
  type: string
}

// Fetch the raw MDX for a page path like "docs/pages/ai-security/overview.mdx".
export async function fetchRawPage(path: string): Promise<string> {
  const url = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/${path}`
  const res = await fetch(url)
  if (!res.ok) {
    throw new Error(`Could not load page (${res.status}). Path: ${path}`)
  }
  return res.text()
}

// List every editable docs page in the repo, grouped by framework and ordered
// to match the live site's sidebar. Excludes files the wizard must never let a
// contributor edit:
//   - index.mdx  -> auto-generated by utils/generate-folder-indexes.js
//   - _*.tsx / _*.css -> Vocs layout/theme internals (e.g. _layout.tsx)
//   - anything that isn't an .mdx under docs/pages/
export async function fetchPageList(): Promise<FrameworkGroup[]> {
  const url = `https://api.github.com/repos/${REPO}/git/trees/${BRANCH}?recursive=1`
  const [res, order] = await Promise.all([fetch(url), fetchSidebarOrder()])
  if (!res.ok) {
    throw new Error(`Could not load page list from GitHub (${res.status}).`)
  }
  const data = (await res.json()) as { tree: TreeNode[]; truncated?: boolean }
  if (data.truncated) {
    // The tree API caps very large repos. Surface it rather than silently
    // showing a partial list.
    console.warn('GitHub tree response was truncated; page list may be incomplete.')
  }

  const pages = data.tree
    .filter((node) => node.type === 'blob' && isEditablePage(node.path))
    .map((node) => toPageEntry(node.path))

  // Only offer pages that actually appear in the site's sidebar. This drops
  // non-sidebar folders like `config/` and `contribute/`. If the sidebar
  // couldn't be read, fall back to showing everything editable.
  const scoped = order.size > 0 ? pages.filter((p) => order.has(p.path)) : pages

  return groupByFramework(scoped, order)
}

// Parse the sidebar order straight from vocs.config.ts so the picker matches
// the live site. The config lists routes in sidebar order as `link: '/a/b'`,
// which map 1:1 to `docs/pages/a/b.mdx`. Returns a Map(path -> order index).
// If the config can't be read, we fall back to alphabetical (order stays empty).
//
// Only the `sidebar` array is read. The file also has a `topNav` above it whose
// two links, Changelog and Contributing, would otherwise score as routes 0 and
// 1, putting a changelog page the sidebar doesn't carry at the very top of the
// picker and floating Contributing above Introduction. Scoping the scan to the
// sidebar gives the real running order: Introduction, the frameworks, Guides,
// SEAL Certifications, then Contributing.
async function fetchSidebarOrder(): Promise<Map<string, number>> {
  try {
    const res = await fetch(
      `https://raw.githubusercontent.com/${REPO}/${BRANCH}/vocs.config.ts`,
    )
    if (!res.ok) return new Map()
    const sidebar = sliceSidebar(await res.text())
    const order = new Map<string, number>()
    let i = 0
    for (const m of sidebar.matchAll(/link:\s*'([^']+)'/g)) {
      const link = m[1]
      if (!link.startsWith('/')) continue // socials and other outbound links
      const route = link.replace(/^\//, '').replace(/\/$/, '')
      const path = `${DOCS_ROOT}${route}.mdx`
      if (!order.has(path)) order.set(path, i++)
    }
    return order
  } catch {
    return new Map()
  }
}

// The text of the `sidebar: [ … ]` array, found by matching brackets so nested
// item arrays don't end it early. Returns '' if there's no sidebar to read,
// which lands the caller on its alphabetical fallback.
function sliceSidebar(text: string): string {
  const start = text.indexOf('[', text.search(/\bsidebar\s*:/))
  if (start < 0) return ''
  let depth = 0
  for (let i = start; i < text.length; i++) {
    if (text[i] === '[') depth++
    else if (text[i] === ']' && --depth === 0) return text.slice(start, i + 1)
  }
  return ''
}

function isEditablePage(path: string): boolean {
  if (!path.startsWith(DOCS_ROOT)) return false
  if (!path.endsWith('.mdx')) return false
  const name = path.slice(path.lastIndexOf('/') + 1)
  if (name === 'index.mdx') return false // auto-generated
  if (name.startsWith('_')) return false // internals
  return true
}

function toPageEntry(path: string): PageEntry {
  const rel = path.slice(DOCS_ROOT.length) // "opsec/passwords/managers.mdx"
  const segments = rel.split('/')
  const framework = segments[0]
  const name = segments[segments.length - 1].replace(/\.mdx$/, '')
  // Any folders between the framework and the file — used to differentiate
  // nested pages (e.g. opsec has many "overview" pages in different subfolders).
  const subdir = segments.slice(1, -1)
  return { path, framework, subdir, name, rel }
}

function groupByFramework(
  pages: PageEntry[],
  order: Map<string, number> = new Map(),
): FrameworkGroup[] {
  // Sort key: sidebar index if present, else Infinity (falls after known
  // pages), tie-broken alphabetically so unlisted pages stay predictable.
  const rank = (p: PageEntry) => order.get(p.path) ?? Infinity

  const groups = new Map<string, PageEntry[]>()
  for (const page of pages) {
    if (!groups.has(page.framework)) groups.set(page.framework, [])
    groups.get(page.framework)!.push(page)
  }

  const result = [...groups.entries()].map(([framework, items]) => ({
    framework,
    // Pages within a framework: sidebar order first, then alphabetical.
    pages: items.sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name)),
    // A framework's rank = its earliest page in the sidebar.
    _rank: Math.min(...items.map(rank)),
  }))

  // Frameworks: sidebar order first, then alphabetical for any not in sidebar.
  return result
    .sort((a, b) => a._rank - b._rank || a.framework.localeCompare(b.framework))
    .map(({ framework, pages }) => ({ framework, pages }))
}

// Fetch the contributor directory (slug -> { name, avatar, github, company … }).
// Used to render the AttributionList preview like the live site. Best-effort:
// returns {} if unavailable.
export async function fetchContributors(): Promise<ContributorDirectory> {
  try {
    const res = await fetch(
      `https://raw.githubusercontent.com/${REPO}/${BRANCH}/docs/pages/config/contributors.json`,
    )
    if (!res.ok) return {}
    return (await res.json()) as ContributorDirectory
  } catch {
    return {}
  }
}

// Split a raw MDX file into its YAML frontmatter block and the body.
// The frontmatter is kept aside and untouched — contributors edit the body
// only. `raw` reassembles losslessly as frontmatter + body.
export function splitFrontmatter(raw: string): {
  frontmatter: string | null
  body: string
} {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw)
  if (!match) {
    return { frontmatter: null, body: raw }
  }
  return { frontmatter: match[1], body: raw.slice(match[0].length) }
}

// Reassemble a full MDX file from frontmatter + (edited) body.
// Kept beside `splitFrontmatter` so the split and the reassembly can't drift
// apart.
export function assembleMdx(frontmatter: string | null | undefined, body: string): string {
  if (frontmatter == null) return body
  return `---\n${frontmatter}\n---\n${body}`
}
