import { splitFrontmatter } from './github.js'
import { joinBlocks, splitBlocks } from './blocks.js'
import { applyDraft, readDraft } from './drafts.js'
import { loadPage } from './newPages.js'
import { PLACEHOLDERS } from './placeholders.js'

// The section map: the list in an overview page of every page in its section,
// one line each on what it covers. The content model asks for one on every
// overview, readers find their way with it, and reviewers ask for a new page's
// row when it's missing. The wizard doesn't add it unasked; it finds the map,
// says whether the new page is on it, and offers to add the row.

const DOCS_ROOT = 'docs/pages/'

// The content model's names for a page-map heading.
const MAP_HEADING =
  /^(#{2,3})\s+(?:what this (?:framework|section) covers|framework structure|section structure|contents|table of contents|pages)\s*$/im

/** A page as it is in this browser: on GitHub, with any draft laid over it. */
export async function currentBody(path: string): Promise<string> {
  const { body } = splitFrontmatter(await loadPage(path))
  const draft = readDraft(path)
  return joinBlocks(draft ? applyDraft(splitBlocks(body), draft).blocks : splitBlocks(body))
}

/**
 * Which overview holds the map for a page: the nearest one up from its folder
 * that has a page-map heading and isn't generated, else the framework's own
 * overview. `index.mdx` files are generated by the docs build and never used.
 */
export async function findMapFile(pagePath: string, existing: Set<string>): Promise<string | null> {
  const folders = pagePath.slice(DOCS_ROOT.length).split('/').slice(0, -1)
  for (let n = folders.length; n >= 1; n--) {
    const candidate = `${DOCS_ROOT}${folders.slice(0, n).join('/')}/overview.mdx`
    if (!existing.has(candidate)) continue
    try {
      const text = await currentBody(candidate)
      if (!text.includes('AUTOGENERATED') && MAP_HEADING.test(text)) return candidate
    } catch {
      /* try the next one up */
    }
  }
  const framework = `${DOCS_ROOT}${folders[0]}/overview.mdx`
  return existing.has(framework) ? framework : null
}

/** Whether the text links to the route. */
export const linksTo = (text: string, route: string) =>
  text.includes(`](${route})`) || text.includes(`](${route}#`)

const ITEM_RE = /^(\s*)(\d+[.)]|[-*+])\s+/
const LINK_RE = /\]\((\/[^)#\s]+)/
const indentOf = (line: string) => line.match(/^\s*/)![0].length

/**
 * The section's text with one row for the new page in its map, placed after
 * the nearest page before it in the sidebar that the map lists (`before`, in
 * order from the nearest), or first if none is. The row copies its neighbours:
 * their indent, numbered or bulleted (renumbering the rows after it), and how
 * they separate the link from its line, `:` or ` — `. The line itself is a
 * placeholder. Null when the text has no map.
 */
export function insertMapRow(text: string, route: string, title: string, before: string[]): string | null {
  const lines = text.split('\n')
  const head = lines.findIndex((l) => MAP_HEADING.test(l))
  if (head < 0) return null
  const level = lines[head].match(/^#+/)![0].length
  let end = lines.findIndex((l, i) => i > head && /^(#+)\s/.test(l) && l.match(/^#+/)![0].length <= level)
  if (end < 0) end = lines.length

  const items: { at: number; indent: number; marker: string; route: string | null }[] = []
  for (let i = head + 1; i < end; i++) {
    const m = ITEM_RE.exec(lines[i])
    if (m) items.push({ at: i, indent: m[1].length, marker: m[2], route: LINK_RE.exec(lines[i])?.[1] ?? null })
  }
  // How the rows separate the link from its line: taken from the rows
  // themselves (and their wrapped lines), not the section's prose.
  const rowText = items.map((it) => {
    let j = it.at + 1
    while (j < end && lines[j].trim() !== '' && !ITEM_RE.test(lines[j])) j++
    return lines.slice(it.at, j).join('\n')
  })
  const sep = rowText.filter((t) => /\)\s*(?:\n\s*)?—/.test(t)).length > rowText.filter((t) => /\)\s*:/.test(t)).length ? ' — ' : ': '
  const label = title.replace(/[[\]]/g, '')

  const anchor = before.map((r) => items.find((it) => it.route === r)).find(Boolean)
  const top = items.length ? Math.min(...items.map((it) => it.indent)) : 0
  const like = anchor ?? items.find((it) => it.indent === top)
  if (!like) {
    // A map heading with no list under it: the row starts one.
    let at = end
    while (at > head + 1 && lines[at - 1].trim() === '') at--
    lines.splice(at, 0, '', `- [${label}](${route})${sep}${PLACEHOLDERS.mapRow}`)
    return lines.join('\n')
  }

  const numbered = /^\d/.test(like.marker)
  const punct = numbered ? like.marker.slice(-1) : ''
  let at: number
  let number = 1
  if (anchor) {
    // After the anchor's whole item: its wrapped lines and sub-items.
    at = anchor.at + 1
    while (at < end && lines[at].trim() !== '' && indentOf(lines[at]) > anchor.indent) at++
    if (numbered) number = parseInt(anchor.marker, 10) + 1
  } else {
    at = like.at
    if (numbered) number = parseInt(like.marker, 10)
  }
  const marker = numbered ? `${number}${punct}` : like.marker
  const row = `${' '.repeat(like.indent)}${marker} [${label}](${route})${sep}${PLACEHOLDERS.mapRow}`

  if (numbered) {
    // The rows after it, at its level, move down one.
    for (let i = at; i < end; i++) {
      const m = ITEM_RE.exec(lines[i])
      if (!m) continue
      if (m[1].length < like.indent) break
      if (m[1].length === like.indent && /^\d/.test(m[2])) {
        lines[i] = lines[i].replace(/^(\s*)(\d+)/, (_x, sp: string, n: string) => `${sp}${parseInt(n, 10) + 1}`)
      }
    }
  }
  lines.splice(at, 0, row)
  return lines.join('\n')
}

/** The map's row for a page, with its placeholder line replaced by `line`. */
export function fillMapRow(text: string, route: string, line: string): string {
  return text
    .split('\n')
    .map((l) => (l.includes(`](${route})`) ? l.replace(PLACEHOLDERS.mapRow, line) : l))
    .join('\n')
}
